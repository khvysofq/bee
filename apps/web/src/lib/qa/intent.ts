/** 判定越界类型；不越界返回 null。传入的应是归一化后的问题文本。 */
export function detectRefusal(normalizedQuestion: string): RefusalCode | null {
  for (const rule of REFUSAL_RULES) {
    if (rule.pattern.test(normalizedQuestion)) return rule.code;
  }
  return null;
}

/** 拒绝话术（含标题与正文），供回答层与测试共用。 */
export function refusalCopy(code: RefusalCode): RefusalCopy {
  return REFUSAL_COPY[code];
}
