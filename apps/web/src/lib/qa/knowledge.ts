/** 对外可读的出处标签（不含文档路径与内部编号）。 */
export function citationOf(entry: KnowledgeEntry): string {
  const label = KNOWLEDGE_DOC_LABEL[entry.source.doc] ?? '站内说明';
  return `${label} · ${entry.title}`;
}

export function knowledgeEntryById(id: string): KnowledgeEntry | undefined {
  return KNOWLEDGE_ENTRIES.find((entry) => entry.id === id);
}
